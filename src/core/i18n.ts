const dictionaries: Record<LanguageCode, Dictionary> = { en, fr, ar, dz };

export function translate(
  lang: LanguageCode,
  key: MessageKey,
  params?: Record<string, string | number>,
): string {
  const dict = dictionaries[lang] ?? en;
  let message: string = dict[key] ?? en[key] ?? key;
  if (params) {
    for (const [name, value] of Object.entries(params)) {
      message = message.split(`{${name}}`).join(String(value));
    }
  }
  return message;
}

export function isRtl(lang: LanguageCode): boolean {
  return lang === 'ar' || lang === 'dz';
}

export function localeFor(lang: LanguageCode): string {
  switch (lang) {
    case 'fr':
      return 'fr-FR';
    case 'ar':
      return 'ar-DZ';
    case 'dz':
      return 'ar-DZ';
    default:
      return 'en-GB';
  }
}

export function formatTime(lang: LanguageCode, at: number): string {
  try {
    return new Intl.DateTimeFormat(localeFor(lang), {
      hour: '2-digit',
      minute: '2-digit',
      second: '2-digit',
    }).format(new Date(at));
  } catch {
    return new Date(at).toLocaleTimeString();
  }
}
